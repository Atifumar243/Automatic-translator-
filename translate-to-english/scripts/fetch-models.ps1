<#
  scripts/fetch-models.ps1 — Windows PowerShell version of fetch-models.mjs.
  Downloads Bergamot models for the OPTIONAL fully-offline engine.

  Run from the extension root, e.g.:
      powershell -ExecutionPolicy Bypass -File scripts\fetch-models.ps1 es fr de it pt ru

  With no args it fetches a default set. You do NOT need this if you only use
  the browser built-in engine (Chrome/Edge 138+).

  The WASM engine (.js/.wasm) is NOT auto-downloaded (no single stable URL).
  Set $WasmJsUrl / $WasmWasmUrl below to fetch them, or copy them manually
  into engines\bergamot\. See fetch-models.mjs comments for sources.
#>

param([Parameter(ValueFromRemainingArguments = $true)] [string[]] $Langs)

$ErrorActionPreference = "Stop"
[Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12

$Root       = Split-Path -Parent $PSScriptRoot
$ModelsDir  = Join-Path $Root "models"
$BergamotDir= Join-Path $Root "engines\bergamot"

$WasmJsUrl   = ""   # -> engines\bergamot\bergamot-translator-worker.js
$WasmWasmUrl = ""   # -> engines\bergamot\bergamot-translator-worker.wasm

$Gh  = "https://api.github.com/repos/mozilla/firefox-translations-models/contents"
$Raw = "https://raw.githubusercontent.com/mozilla/firefox-translations-models/main"
$Channels = @("prod", "dev")
$DefaultLangs = @("es", "fr", "de", "it", "pt", "ru", "nl", "pl")

if (-not $Langs -or $Langs.Count -eq 0) { $Langs = $DefaultLangs }
$Headers = @{ "User-Agent" = "translate-to-english-fetch" }

function Get-Bytes([string]$Url) {
  $wc = New-Object System.Net.WebClient
  $wc.Headers.Add("User-Agent", "translate-to-english-fetch")
  return $wc.DownloadData($Url)
}

function Expand-Gzip([byte[]]$Bytes) {
  $in  = New-Object System.IO.MemoryStream (,$Bytes)
  $gz  = New-Object System.IO.Compression.GZipStream($in, [System.IO.Compression.CompressionMode]::Decompress)
  $out = New-Object System.IO.MemoryStream
  $gz.CopyTo($out); $gz.Dispose(); $in.Dispose()
  return $out.ToArray()
}

function Get-Role([string]$Name) {
  if ($Name -match '^model\..*\.bin(\.gz)?$')     { return "model" }
  if ($Name -match '^lex\..*\.bin(\.gz)?$')        { return "lex" }
  if ($Name -match '^vocab\..*\.spm(\.gz)?$')      { return "vocab" }
  if ($Name -match '^srcvocab\..*\.spm(\.gz)?$')   { return "srcvocab" }
  if ($Name -match '^trgvocab\..*\.spm(\.gz)?$')   { return "trgvocab" }
  return $null
}

function Get-Gemm([string]$ModelName) {
  if ($ModelName -match 'intgemm\.alphas') { return "int8shiftAlphaAll" }
  if ($ModelName -match 'intgemm')          { return "int8shiftAll" }
  return "int8shiftAlphaAll"
}

New-Item -ItemType Directory -Force -Path $ModelsDir | Out-Null
$pairs = @{}

foreach ($lang in $Langs) {
  $pair = "$lang" + "en"
  Write-Host "$lang -> en:"
  $listing = $null; $channel = $null
  foreach ($ch in $Channels) {
    try {
      $listing = Invoke-RestMethod -Uri "$Gh/models/$ch/$pair" -Headers $Headers
      if ($listing) { $channel = $ch; break }
    } catch { $listing = $null }
  }
  if (-not $listing) { Write-Warning "  x $pair not found (skipping)"; continue }

  $roles = @{}
  foreach ($f in $listing) {
    $role = Get-Role $f.name
    if ($role -and -not $roles.ContainsKey($role)) { $roles[$role] = $f.name }
  }
  $hasVocab = $roles.ContainsKey("vocab") -or ($roles.ContainsKey("srcvocab") -and $roles.ContainsKey("trgvocab"))
  if (-not ($roles.ContainsKey("model") -and $roles.ContainsKey("lex") -and $hasVocab)) {
    Write-Warning "  x $pair incomplete file set (skipping)"; continue
  }

  $outDir = Join-Path $ModelsDir $pair
  New-Item -ItemType Directory -Force -Path $outDir | Out-Null

  $entry = @{ gemm = (Get-Gemm $roles["model"]) }
  foreach ($role in $roles.Keys) {
    $fname = $roles[$role]
    $bytes = Get-Bytes "$Raw/models/$channel/$pair/$fname"
    $outName = $fname
    if ($fname.EndsWith(".gz")) { $bytes = Expand-Gzip $bytes; $outName = $fname.Substring(0, $fname.Length - 3) }
    [System.IO.File]::WriteAllBytes((Join-Path $outDir $outName), $bytes)
    $entry[$role] = $outName
    Write-Host ("    - {0} ({1:N1} MB)" -f $fname, ($bytes.Length / 1MB))
  }
  $pairs[$pair] = $entry
  Write-Host "  ok $pair"
}

$registry = @{
  generated = (Get-Date).ToString("o")
  note = "Auto-generated by scripts/fetch-models.ps1. Each pair is <src>en."
  pairs = $pairs
}
($registry | ConvertTo-Json -Depth 6) | Out-File -FilePath (Join-Path $ModelsDir "registry.json") -Encoding utf8
Write-Host "`nWrote models\registry.json with $($pairs.Count) pair(s)."

if ($WasmJsUrl -and $WasmWasmUrl) {
  New-Item -ItemType Directory -Force -Path $BergamotDir | Out-Null
  Write-Host "Fetching WASM engine..."
  [System.IO.File]::WriteAllBytes((Join-Path $BergamotDir "bergamot-translator-worker.js"),  (Get-Bytes $WasmJsUrl))
  [System.IO.File]::WriteAllBytes((Join-Path $BergamotDir "bergamot-translator-worker.wasm"),(Get-Bytes $WasmWasmUrl))
  Write-Host "  ok WASM engine saved"
} else {
  Write-Host "`nWASM engine not fetched (WasmJsUrl/WasmWasmUrl blank). The built-in"
  Write-Host "browser engine works without it. See fetch-models.mjs comments for sources."
}
Write-Host "`nDone."
